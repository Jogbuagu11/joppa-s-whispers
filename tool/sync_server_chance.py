#!/usr/bin/env python3
"""Copies the prize tables in content/chance.json into the server's roll
function, so the server draws from exactly the table players are shown.

Run from the project folder after any change to the prizes or their
weights in content/chance.json (and raise "tables_version" there first):
    python3 tool/sync_server_chance.py
A server test fails if this is forgotten."""
import json

chance = json.load(open('content/chance.json'))
version = json.load(open('content/version.json'))['version']
tables = {
    'wheel': chance['wheel']['prizes'],
    'jars': {kind: jar['prizes'] for kind, jar in chance['jars']['kinds'].items()},
}
out = (
    '// GENERATED by tool/sync_server_chance.py from content/chance.json.\n'
    '// Do not edit by hand: change the content file and run the tool.\n'
    "import type { Tables } from './rules.ts';\n\n"
    '// Which set of tables these are (chance.json, "tables_version"); the\n'
    '// content version they were copied at is kept for the record only.\n'
    f"export const TABLES_VERSION = {chance['tables_version']};\n"
    f'export const CONTENT_VERSION = {version};\n\n'
    '// deno-fmt-ignore\n'
    f'export const TABLES: Tables = {json.dumps(tables, indent=2)};\n'
)
open('supabase/functions/roll/tables.ts', 'w').write(out)
print('Wrote supabase/functions/roll/tables.ts for content version', version)
